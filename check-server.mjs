import assert from 'node:assert/strict';
import {validSession,validWorkspace} from './lib/school-validation.mjs';
assert(validWorkspace({profiles:[{id:'student-1',name:'Ylli 01',grade:1}],custom:[]}));
assert(!validWorkspace({profiles:[{id:'x',name:'A',grade:1},{id:'x',name:'B',grade:1}],custom:[]}));
assert(validWorkspace({profiles:[{id:'x',name:'A',grade:5}],custom:[]}));
assert(!validWorkspace({profiles:[{id:'x',name:'A',grade:6}],custom:[]}));
const question={id:'q1',grade:1,cat:'logic',title:'Sa?',visual:'',options:['1','2','3'],answer:'2',hint:'Numëro',explain:'Dy'};
assert(validWorkspace({profiles:[],custom:[question]}));
assert(!validWorkspace({profiles:[],custom:[{...question,grade:5}]}));
assert(!validWorkspace({profiles:[],custom:[{...question,answer:'4'}]}));
assert(!validWorkspace({profiles:[],custom:[{...question,options:['2','2','3']}]}));
assert(validSession({id:'s1',grade:2,answers:[{cat:'whatif',correct:true,question:'Pse?',note:'Sepse…'}]}));
assert(!validSession({id:'s1',grade:5,answers:[{cat:'whatif',correct:true,question:'Pse?'}]}));
assert(!validSession({id:'s1',grade:2,answers:[{cat:'whatif',correct:'true',question:'Pse?'}]}));
assert(!validSession({id:'s1',grade:2,answers:[]}));
assert(!validSession({id:'s1',grade:2,answers:Array(11).fill({cat:'math',correct:true,question:'Pse?'})}));
console.log('Server validation rejects duplicate identities, malformed questions and invalid sessions.');
