import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url),hull=require('./safe-hull/index.cjs'),loader=require('./source-loader.cjs');
const themeColors=require('./theme-colors.cjs');
const read=file=>readFileSync(new URL(file,import.meta.url),'utf8');
const square=[[0,0],[2,0],[2,2],[0,2],[1,1],[0,0]];
assert.deepEqual(hull(square,Infinity),[[0,0],[2,0],[2,2],[0,2],[0,0]]);
assert.deepEqual(hull([[1,0],[0,0],[2,0],[3,0]],Infinity),[[0,0],[3,0],[0,0]]);
assert.deepEqual(hull([],Infinity),[]);
assert.deepEqual(hull([[1,1],[1,1],[1,1],[1,1]],Infinity),[[1,1],[1,1]]);
assert.deepEqual(square,[[0,0],[2,0],[2,2],[0,2],[1,1],[0,0]]);
assert.throws(()=>hull(square,Infinity,['.x','.y']),TypeError);
assert.throws(()=>hull(square,10),TypeError);
const transform=(file,source=read('./node_modules/@scratch/'+file))=>loader.call({resourcePath:'/node_modules/@scratch/'+file},source);
const manager=transform('scratch-vm/src/extension-support/extension-manager.js');
assert.ok(manager.includes("if (!['pen','music'].includes(extensionURL))"));
assert.ok(!manager.includes("require('../extensions/scratch3_video_sensing')"));
assert.throws(()=>transform('scratch-vm/src/extension-support/extension-manager.js',''),/Unsupported/);
const picker=transform('scratch-gui/src/lib/libraries/extensions/index.jsx');
assert.ok(!picker.includes('defaultMessage="Video Sensing"'));
assert.ok(picker.includes('defaultMessage="Music"')&&picker.includes('defaultMessage="Pen"'));
for(const [name,version] of [['decode-uri-component','0.5.1'],['uuid','11.1.1'],['cookie','0.7.2']])assert.equal(JSON.parse(read('./node_modules/'+name+'/package.json')).version,version);
assert.ok(!read('./build-source.mjs').includes("globalObject:'window'"));
assert.ok(read('./build-source.mjs').includes("exportLocalsConvention:'camelCase'"));
assert.ok(read('./build-source.mjs').includes("exclude:resolve(modules,'scratch-render-fonts')"),'Inline base64 font imports must not become asset URLs');
assert.ok(read('./vite.config.mjs').includes("replacement:resolve(root,'browser-storage.mjs')"));
const scratchColors='/node_modules/@scratch/scratch-gui/src/css/colors.css';
assert.match(themeColors(scratchColors,read('./node_modules/@scratch/scratch-gui/src/css/colors.css')),/\$motion-primary:\s*#32834f;/,'Scratch loading screen uses the app green');
assert.ok(read('./source-entry.mjs').includes("export {ScratchStorage} from '@scratch/scratch-storage'"));
const sounds=transform('scratch-gui/src/containers/sound-tab.jsx');
assert.ok(!sounds.includes('title: intl.formatMessage(messages.recordSound)'));
assert.throws(()=>transform('scratch-gui/src/containers/sound-tab.jsx',''),/Unsupported/);
for(const name of ['color-mode','theme']){
 const file='scratch-gui/src/lib/settings/'+name+'/persistence.js';
 assert.ok(!transform(file).includes('document.cookie'));
 assert.throws(()=>transform(file,''),/Unsupported/);
}
const queryFile='/node_modules/query-string/index.js';
const querySource=loader.call({resourcePath:queryFile},read('./node_modules/query-string/index.js'));
const queryExports={};
new Function('require','exports',querySource)(require,queryExports);
assert.deepEqual({...queryExports.parse('?bridge=private-session&title=P%C3%ABrsh%C3%ABndetje')},{bridge:'private-session',title:'Përshëndetje'});
assert.doesNotThrow(()=>queryExports.parse('?title=%E0%A4%A'));
assert.throws(()=>loader.call({resourcePath:queryFile},''),/Unsupported/);
console.log('Source security: numeric convex hull, rejected dynamic formats, restricted extension registry/picker, pinned corrected dependencies, bridge query decoding and worker-compatible globals passed.');
