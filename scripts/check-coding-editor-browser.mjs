import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import JSZip from '../coding-editor/node_modules/jszip/lib/index.js';

const base=process.env.CODING_EDITOR_TEST_URL||'http://localhost:5184';
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[],external=[],warnings=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()!=='error')return;if(message.text().startsWith('Warning: '))warnings.push(message.text());else errors.push(message.text()+' '+message.location().url);});
 page.on('request',request=>{if(new URL(request.url()).protocol.startsWith('http')&&new URL(request.url()).origin!==new URL(base).origin)external.push(request.url());});
 await page.goto(base);
 await page.getByRole('button',{name:'Shkarko projektin',exact:true}).waitFor();
 await page.waitForFunction(()=>window.codingLab?.store.getState().scratchGui.projectState.loadingState==='SHOWING_WITHOUT_ID');
 assert.equal(await page.getByRole('tab',{name:'Kodi',exact:true}).count(),1);
 assert.equal(await page.getByRole('tab',{name:'Veshjet',exact:true}).count(),1);
 assert.equal(await page.getByRole('tab',{name:'Tingujt',exact:true}).count(),1);
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Shkarko projektin',exact:true}).click();
 const download=await downloaded,path=await download.path();
 const {readFile}=await import('node:fs/promises');
 const bytes=await readFile(path),zip=await JSZip.loadAsync(bytes);
 const project=JSON.parse(await zip.file('project.json').async('string'));
 assert.equal(project.targets.find(target=>!target.isStage).name,'Macja');
 assert(project.targets.find(target=>!target.isStage).costumes.length>0);
 page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'Projekt i ri',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Projekti i ri u hap.'}).waitFor();
 assert.equal(await page.evaluate(()=>Object.keys(window.codingLab.vm.editingTarget.blocks._blocks).length),0);
 await page.locator('input[type=file][accept=".sb3"]').setInputFiles({name:'projekti-im.sb3',mimeType:'application/octet-stream',buffer:bytes});
 await page.getByRole('status').filter({hasText:'Projekti u hap nga kompjuteri.'}).waitFor();
 assert.equal(await page.evaluate(()=>window.codingLab.vm.editingTarget.x),0);
 await page.locator('input[type=file][accept=".sb3"]').setInputFiles({name:'gabim.sb3',mimeType:'application/octet-stream',buffer:Buffer.from('not a zip')});
 await page.getByRole('alert').filter({hasText:'vlefshëm'}).waitFor();
 assert.equal(await page.evaluate(()=>window.codingLab.vm.editingTarget.x),0);
 await page.locator('input[type=file][accept=".sb3"]').setInputFiles({name:'shume-i-madh.sb3',mimeType:'application/octet-stream',buffer:Buffer.alloc(10*1024*1024+1)});
 await page.getByRole('alert').filter({hasText:'deri në 10 MB'}).waitFor();
 assert.equal(await page.evaluate(()=>window.codingLab.vm.editingTarget.x),0);
 const unexpected=await zip.file('project.json',JSON.stringify({...project,extensionURLs:{pen:'https://example.invalid/extension.js'}})).generateAsync({type:'nodebuffer'});
 await page.locator('input[type=file][accept=".sb3"]').setInputFiles({name:'me-shtese.sb3',mimeType:'application/octet-stream',buffer:unexpected});
 await page.getByRole('alert').filter({hasText:'Lejohen vetëm projekte'}).waitFor();
 assert.equal(await page.evaluate(()=>window.codingLab.vm.editingTarget.x),0);
 await page.getByRole('tab',{name:'Veshjet',exact:true}).click();
 await page.getByRole('button',{name:'Zhbëj',exact:true}).waitFor();
 await page.getByRole('tab',{name:'Tingujt',exact:true}).click();
 await page.getByRole('button',{name:'Zgjidh një tingull',exact:true}).first().click();
 await page.getByRole('dialog').getByText('Zilja e derës',{exact:true}).click();
 await page.waitForFunction(()=>window.codingLab.vm.editingTarget.sprite.sounds.length===2);
 await page.getByRole('button',{name:'Luaj',exact:true}).click();
 await page.getByRole('tab',{name:'Kodi',exact:true}).click();
 await page.getByRole('button',{name:'Zgjidh një personazh',exact:true}).first().click();
 await page.getByRole('dialog').getByText('Topi',{exact:true}).click();
 await page.waitForFunction(()=>window.codingLab.vm.runtime.targets.length===3);
 await page.getByRole('button',{name:'Zgjidh një sfond',exact:true}).first().click();
 await page.getByRole('dialog').getByText('Pylli',{exact:true}).click();
 await page.waitForFunction(()=>window.codingLab.vm.runtime.getTargetForStage().sprite.costumes.length===2);
 for(const name of ['Lapsi','Muzika']){
  await page.getByRole('button',{name:'Shto shtesë',exact:true}).click();
  await page.getByRole('dialog').getByText(name,{exact:true}).waitFor();
  if(name==='Lapsi')await page.getByRole('dialog').getByText('Muzika',{exact:true}).waitFor();
  await page.getByRole('dialog').getByText(name,{exact:true}).click();
 }
 await page.waitForFunction(()=>window.codingLab.vm.extensionManager.isExtensionLoaded('pen')&&window.codingLab.vm.extensionManager.isExtensionLoaded('music'));
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'The page shell must fit mobile screens');
 assert(await page.locator('.editor-scroll').evaluate(element=>element.scrollWidth>element.clientWidth),'The wide editor must have an internal scrollbar');
 await page.screenshot({path:'coding-editor/build/editor-mobile.png',fullPage:true});
 console.log('React development warnings:',warnings.length);
 assert.deepEqual(errors,[]);
 assert.deepEqual(external,[],'The tested default project must not contact external services');
 console.log('Editor browser: Albanian tabs, original robot, SB3 download/reopen, corrupted/oversized/unexpected file protection, costume editor and mobile shell passed.');
}finally{await browser.close();}
